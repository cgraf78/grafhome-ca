//! Render non-secret deployment files from policy and config.
//!
//! Rendering writes into a caller-provided staging directory. It does not write
//! to `/etc`, `/srv`, or any live host path directly; deployment remains a
//! separate operator-controlled phase.

use std::collections::{BTreeMap, BTreeSet};
use std::net::IpAddr;
use std::path::{Component, Path, PathBuf};

use serde_json::{Value, json};

use crate::error::{Error, Result};
use crate::model::SiteModel;
use crate::policy::{
    CA_POLICY_PATH, ENDPOINT_ROLE_CA_API, ENDPOINT_ROLE_CA_ORIGIN, HOST_POLICY_DIR, Host,
    PROVISIONER_ROLE_HOST_BOOTSTRAP, PROVISIONER_ROLE_PROXY_X509, PROVISIONER_ROLE_USER_ENROLLMENT,
    Provisioner, SshRole, USERS_POLICY_PATH, ca_policy_field, host_policy_field, step_max_ttl,
};

/// File generated by the renderer.
#[derive(Debug, Clone, Eq, PartialEq)]
pub struct RenderedFile {
    /// Relative path under the staging directory.
    pub path: PathBuf,
    /// Unix file mode intended for install.
    pub mode: u32,
    /// Rendered file contents.
    pub content: String,
}

/// Render all currently modeled deployment files.
pub fn render(model: &SiteModel) -> Result<Vec<RenderedFile>> {
    let mut files = Vec::new();
    let ca_origin = required_endpoint(model, ENDPOINT_ROLE_CA_ORIGIN)?;
    let ca_host = required_host(model, &ca_origin.target)?;
    let variables = variables(model)?;

    files.push(RenderedFile {
        path: host_path(
            &ca_host.host,
            absolute_child(model.deployment.ca_steppath(), "config/ca.json")?,
        )?,
        mode: 0o640,
        content: render_template(
            include_str!("../templates/step-ca/ca.json.template"),
            &variables,
        )?,
    });
    files.push(RenderedFile {
        path: host_path(&ca_host.host, "etc/systemd/system/step-ca.service")?,
        mode: 0o644,
        content: render_template(
            include_str!("../templates/systemd/step-ca.service.template"),
            &variables,
        )?,
    });
    files.push(RenderedFile {
        path: host_path(&ca_host.host, "usr/libexec/grafhome-ca-wait-origin")?,
        mode: 0o755,
        content: include_str!("../templates/systemd/grafhome-ca-wait-origin").to_owned(),
    });

    for host in model
        .policy
        .hosts
        .iter()
        .filter(|host| host.has_ssh_role(SshRole::Server))
    {
        files.push(RenderedFile {
            path: host_path(
                &host.host,
                absolute_child(
                    &model.deployment.values["GRAFHOME_CA_SSH_TRUST_DIR"],
                    "user_ca_keys.pem",
                )?,
            )?,
            mode: 0o644,
            content: String::new(),
        });
        files.push(RenderedFile {
            path: host_path(
                &host.host,
                absolute_child(
                    &model.deployment.values["GRAFHOME_CA_SSH_TRUST_DIR"],
                    "revoked_user_certs",
                )?,
            )?,
            mode: 0o644,
            content: revoked_ssh_key_source(model, true),
        });
        files.push(RenderedFile {
            path: host_path(
                &host.host,
                absolute_child(
                    variables
                        .get("GRAFHOME_CA_SYSTEM_SSH_DIR")
                        .map(String::as_str)
                        .unwrap_or("/etc/ssh"),
                    "sshd_config.d/grafhome-ca.conf",
                )?,
            )?,
            mode: 0o644,
            content: render_template(
                include_str!("../templates/sshd_config.d/grafhome-ca.conf.template"),
                &variables,
            )?,
        });
        for principal_file in authorized_principals(model, host)? {
            files.push(principal_file);
        }
    }

    for host in model
        .policy
        .hosts
        .iter()
        .filter(|host| host.has_ssh_role(SshRole::Client))
    {
        files.push(RenderedFile {
            path: host_path(
                &host.host,
                absolute_child(
                    &model.deployment.values["GRAFHOME_CA_SSH_TRUST_DIR"],
                    "revoked_host_keys",
                )?,
            )?,
            mode: 0o644,
            content: revoked_ssh_key_source(model, false),
        });
        files.push(RenderedFile {
            path: host_path(
                &host.host,
                absolute_child(
                    &model.deployment.values["GRAFHOME_CA_SSH_TRUST_DIR"],
                    "ssh_known_hosts",
                )?,
            )?,
            mode: 0o644,
            content: String::new(),
        });
        files.push(RenderedFile {
            path: host_path(
                &host.host,
                absolute_child(
                    variables
                        .get("GRAFHOME_CA_SYSTEM_SSH_DIR")
                        .map(String::as_str)
                        .unwrap_or("/etc/ssh"),
                    "ssh_config.d/grafhome-ca.conf",
                )?,
            )?,
            mode: 0o644,
            content: render_template(
                include_str!("../templates/ssh_config.d/grafhome-ca.conf.template"),
                &variables,
            )?,
        });
    }

    files.sort_by(|left, right| left.path.cmp(&right.path));
    Ok(files)
}

fn revoked_ssh_key_source(model: &SiteModel, user_keys: bool) -> String {
    let mut keys = model
        .policy
        .revoked_ssh_keys
        .iter()
        .filter(|entry| entry.is_user() == user_keys)
        .map(|entry| entry.public_key())
        .collect::<Vec<_>>();
    keys.sort_unstable();
    keys.dedup();
    if keys.is_empty() {
        String::new()
    } else {
        format!("{}\n", keys.join("\n"))
    }
}

const TEST_FIXTURE_PATH_PREFIX: &str = "/dev/null/grafhome-ca-test-fixture";

/// Render a JSON fixture with JWK placeholders replaced by public-key provisioners.
///
/// This output is for local validation only. It intentionally rewrites live CA state paths
/// to unusable fixture paths and does not include JWK private material or encrypted
/// provisioner keys. Runtime rollout must still replace placeholders with
/// operator-generated Smallstep provisioner objects.
pub fn materialize_test_ca_fixture_json(model: &SiteModel) -> Result<String> {
    let mut config: Value =
        serde_json::from_str(&rendered_ca_json(model)?).map_err(|source| Error::Json {
            path: PathBuf::from("templates/step-ca/ca.json.template"),
            source,
        })?;
    materialize_test_ca_fixture_state(&mut config)?;
    let provisioners = config
        .pointer_mut("/authority/provisioners")
        .and_then(Value::as_array_mut)
        .ok_or_else(|| Error::Validation {
            field: "templates/step-ca/ca.json.template:authority.provisioners".to_owned(),
            message: "expected provisioners array".to_owned(),
        })?;
    let mut replacements = BTreeMap::new();
    for provisioner in model
        .policy
        .provisioners
        .iter()
        .filter(|entry| entry.status.is_active() && entry.r#type == "JWK")
    {
        replacements.insert(
            provisioner_placeholder(&provisioner.name),
            test_jwk_provisioner(provisioner)?,
        );
    }

    for item in provisioners.iter_mut() {
        let Some(placeholder) = item.as_str() else {
            continue;
        };
        if !placeholder.starts_with("RUNTIME_SECRET_PLACEHOLDER:") {
            continue;
        }
        let replacement = replacements
            .remove(placeholder)
            .ok_or_else(|| Error::Validation {
                field: "templates/step-ca/ca.json.template:authority.provisioners".to_owned(),
                message: format!("unknown runtime placeholder {placeholder}"),
            })?;
        *item = replacement;
    }

    if let Some((placeholder, _)) = replacements.into_iter().next() {
        return Err(Error::Validation {
            field: "templates/step-ca/ca.json.template:authority.provisioners".to_owned(),
            message: format!("missing runtime placeholder {placeholder}"),
        });
    }
    serde_json::to_string_pretty(&config).map_err(|source| Error::Json {
        path: PathBuf::from("templates/step-ca/ca.json.template"),
        source,
    })
}

fn materialize_test_ca_fixture_state(config: &mut Value) -> Result<()> {
    let replacements = [
        ("/root", "step/certs/root_ca.crt"),
        ("/crt", "step/certs/intermediate_ca.crt"),
        ("/key", "step/secrets/intermediate_ca_key"),
        ("/db/dataSource", "step/db"),
        ("/db/valueDir", "step/valuedb"),
        ("/ssh/hostKey", "step/secrets/ssh_host_ca_key"),
        ("/ssh/userKey", "step/secrets/ssh_user_ca_key"),
    ];
    for (pointer, suffix) in replacements {
        let Some(value) = config.pointer_mut(pointer) else {
            return Err(Error::Validation {
                field: format!("templates/step-ca/ca.json.template:{pointer}"),
                message: "missing field needed for test fixture materialization".to_owned(),
            });
        };
        *value = json!(format!("{TEST_FIXTURE_PATH_PREFIX}/{suffix}"));
    }
    let Some(address) = config.pointer_mut("/address") else {
        return Err(Error::Validation {
            field: "templates/step-ca/ca.json.template:/address".to_owned(),
            message: "missing field needed for test fixture materialization".to_owned(),
        });
    };
    *address = json!("127.0.0.1:0");
    Ok(())
}

/// Write rendered files under a staging directory.
pub fn write(files: &[RenderedFile], out_dir: impl AsRef<Path>) -> Result<()> {
    let out_dir = out_dir.as_ref();
    prepare_output_root(out_dir)?;
    write_prepared(files, out_dir)
}

/// Write rendered files after first removing stale files from the staging directory.
pub fn write_clean(files: &[RenderedFile], out_dir: impl AsRef<Path>) -> Result<()> {
    let out_dir = out_dir.as_ref();
    if out_dir.exists() {
        ensure_not_symlink(out_dir)?;
        if !out_dir.is_dir() {
            return Err(Error::Validation {
                field: out_dir.display().to_string(),
                message: "render output path must be a directory".to_owned(),
            });
        }
        remove_generated_roots(files, out_dir)?;
    }
    prepare_output_root(out_dir)?;
    write_prepared(files, out_dir)
}

fn write_prepared(files: &[RenderedFile], out_dir: &Path) -> Result<()> {
    for file in files {
        ensure_relative(&file.path)?;
        let target = out_dir.join(&file.path);
        if let Some(parent) = target.parent() {
            create_dir_all_without_symlinks(out_dir, parent)?;
        }
        ensure_not_symlink(&target)?;
        std::fs::write(&target, &file.content).map_err(|source| Error::io(&target, source))?;
        set_mode(&target, file.mode)?;
    }
    Ok(())
}

fn remove_children(dir: &Path) -> Result<()> {
    for entry in std::fs::read_dir(dir).map_err(|source| Error::io(dir, source))? {
        let entry = entry.map_err(|source| Error::io(dir, source))?;
        let path = entry.path();
        remove_existing_path(&path)?;
    }
    Ok(())
}

fn remove_generated_roots(files: &[RenderedFile], out_dir: &Path) -> Result<()> {
    for root in generated_roots(files)? {
        remove_existing_path(&out_dir.join(root))?;
    }
    Ok(())
}

fn generated_roots(files: &[RenderedFile]) -> Result<BTreeSet<PathBuf>> {
    let mut roots = BTreeSet::new();
    for file in files {
        ensure_relative(&file.path)?;
        let mut root = None;
        for component in file.path.components() {
            match component {
                Component::CurDir => {}
                Component::Normal(part) => {
                    root = Some(PathBuf::from(part));
                    break;
                }
                _ => {
                    return Err(Error::Validation {
                        field: file.path.display().to_string(),
                        message: "unsupported staging path component".to_owned(),
                    });
                }
            }
        }
        let root = root.ok_or_else(|| Error::Validation {
            field: file.path.display().to_string(),
            message: "rendered path must name a file under the output directory".to_owned(),
        })?;
        roots.insert(root);
    }
    Ok(roots)
}

fn remove_existing_path(path: &Path) -> Result<()> {
    let metadata = match std::fs::symlink_metadata(path) {
        Ok(metadata) => metadata,
        Err(source) if source.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(source) => return Err(Error::io(path, source)),
    };
    if metadata.is_dir() && !metadata.file_type().is_symlink() {
        remove_children(path)?;
        std::fs::remove_dir(path).map_err(|source| Error::io(path, source))?;
    } else {
        std::fs::remove_file(path).map_err(|source| Error::io(path, source))?;
    }
    Ok(())
}

fn required_endpoint<'a>(model: &'a SiteModel, role: &str) -> Result<&'a crate::policy::Endpoint> {
    model
        .policy
        .endpoint(role)
        .ok_or_else(|| Error::Validation {
            field: format!("{CA_POLICY_PATH}:endpoints.{role}"),
            message: "missing required endpoint".to_owned(),
        })
}

fn required_host<'a>(model: &'a SiteModel, name: &str) -> Result<&'a Host> {
    model.policy.host(name).ok_or_else(|| Error::Validation {
        field: host_policy_field(name, "host"),
        message: "missing required host".to_owned(),
    })
}

fn variables(model: &SiteModel) -> Result<BTreeMap<String, String>> {
    let mut variables = model.deployment.values.clone();
    variables
        .entry("GRAFHOME_CA_SYSTEM_SSH_DIR".to_owned())
        .or_insert_with(|| "/etc/ssh".to_owned());
    variables
        .entry("GRAFHOME_CA_AUTH_PRINCIPALS_FILE".to_owned())
        .or_insert_with(|| {
            format!(
                "{}/%u",
                model.deployment.values["GRAFHOME_CA_AUTH_PRINCIPALS_DIR"]
            )
        });
    variables
        .entry("GRAFHOME_CA_STRICT_MODES".to_owned())
        .or_insert_with(|| "yes".to_owned());
    variables
        .entry("GRAFHOME_CA_AUTHORIZED_KEYS_DIRECTIVE".to_owned())
        .or_default();
    let ca_api = required_endpoint(model, ENDPOINT_ROLE_CA_API)?;
    let ca_origin = required_endpoint(model, ENDPOINT_ROLE_CA_ORIGIN)?;
    variables.insert(
        "GRAFHOME_CA_API_DNS_NAME".to_owned(),
        ca_api.dns_name.clone(),
    );
    variables.insert(
        "GRAFHOME_CA_ORIGIN_DNS_NAME".to_owned(),
        ca_origin.dns_name.clone(),
    );
    variables.insert(
        "GRAFHOME_CA_ORIGIN_PORT".to_owned(),
        ca_origin.port.to_string(),
    );
    variables.insert(
        "GRAFHOME_CA_ORIGIN_ADDRESS".to_owned(),
        ca_origin.address.clone(),
    );
    variables.insert(
        "GRAFHOME_CA_SSH_CA_ONLY_HOSTS".to_owned(),
        ca_only_host_block(
            &model.policy.ssh_server_principals(),
            &model.deployment.values["GRAFHOME_CA_SSH_TRUST_DIR"],
        ),
    );
    variables.insert(
        "GRAFHOME_CA_HOST_CERT_PATH".to_owned(),
        format!("{}-cert.pub", variables["GRAFHOME_CA_HOST_KEY_PATH"]),
    );
    variables.insert(
        "GRAFHOME_CA_X509_ALLOWED_DNS_JSON".to_owned(),
        x509_allowed_dns_json(&model.policy)?,
    );
    variables.insert(
        "GRAFHOME_CA_SSH_USER_ALLOWED_PRINCIPALS_JSON".to_owned(),
        ssh_user_allowed_principals_json(model)?,
    );
    let (host_dns, host_ips) = ssh_host_allowed_principals_json(model)?;
    variables.insert("GRAFHOME_CA_SSH_HOST_ALLOWED_DNS_JSON".to_owned(), host_dns);
    variables.insert("GRAFHOME_CA_SSH_HOST_ALLOWED_IPS_JSON".to_owned(), host_ips);
    variables.insert(
        "GRAFHOME_CA_PROVISIONERS_JSON".to_owned(),
        provisioners_json(&model.policy.provisioners)?,
    );
    Ok(variables)
}

fn ssh_user_allowed_principals_json(model: &SiteModel) -> Result<String> {
    let mut principals = model
        .policy
        .users
        .iter()
        .filter(|user| user.status.is_active())
        .map(|user| user.principal.as_str())
        .collect::<Vec<_>>();
    principals.sort_unstable();
    principals.dedup();
    serde_json::to_string(&principals).map_err(|source| Error::Json {
        path: PathBuf::from(USERS_POLICY_PATH),
        source,
    })
}

fn ssh_host_allowed_principals_json(model: &SiteModel) -> Result<(String, String)> {
    let mut dns = BTreeSet::new();
    let mut ips = BTreeSet::new();
    for principal in model.policy.hosts.iter().flat_map(|host| &host.principals) {
        if principal.parse::<IpAddr>().is_ok() {
            ips.insert(principal.as_str());
        } else {
            dns.insert(principal.as_str());
        }
    }
    let path = PathBuf::from(HOST_POLICY_DIR);
    let dns = serde_json::to_string(&dns).map_err(|source| Error::Json {
        path: path.clone(),
        source,
    })?;
    let ips = serde_json::to_string(&ips).map_err(|source| Error::Json { path, source })?;
    Ok((dns, ips))
}

fn x509_allowed_dns_json(policy: &crate::policy::Policy) -> Result<String> {
    serde_json::to_string(&policy.x509_allowed_dns()).map_err(|source| Error::Json {
        path: PathBuf::from(CA_POLICY_PATH),
        source,
    })
}

fn rendered_ca_json(model: &SiteModel) -> Result<String> {
    render_template(
        include_str!("../templates/step-ca/ca.json.template"),
        &variables(model)?,
    )
}

/// Return the authority policy rendered from the current site policy.
pub fn ca_authority_policy(model: &SiteModel) -> Result<Value> {
    let path = PathBuf::from("rendered/step/config/ca.json");
    let config: Value =
        serde_json::from_str(&rendered_ca_json(model)?).map_err(|source| Error::Json {
            path: path.clone(),
            source,
        })?;
    config
        .pointer("/authority/policy")
        .cloned()
        .ok_or_else(|| Error::Validation {
            field: path.display().to_string(),
            message: "rendered CA configuration is missing authority policy".to_owned(),
        })
}

fn provisioners_json(provisioners: &[Provisioner]) -> Result<String> {
    let mut rendered = Vec::new();
    // Retired ACME rows stay readable policy but must never reach a CA.
    for provisioner in provisioners
        .iter()
        .filter(|entry| entry.status.is_active() && entry.role != PROVISIONER_ROLE_PROXY_X509)
    {
        let value = match provisioner.r#type.as_str() {
            "JWK" => json!(provisioner_placeholder(&provisioner.name)),
            other => {
                return Err(Error::Validation {
                    field: ca_policy_field("provisioners", &provisioner.role, "type"),
                    message: format!("rendering provisioner type {other} is not implemented"),
                });
            }
        };
        rendered.push(value);
    }
    serde_json::to_string_pretty(&rendered).map_err(|source| Error::Json {
        path: PathBuf::from(CA_POLICY_PATH),
        source,
    })
}

/// Render the Smallstep claims object for one active provisioner.
///
/// The integration test uses this same policy-to-JSON path when it swaps
/// test-only generated JWK public keys into the rendered config. Keeping that
/// path shared prevents daemon-boot tests from masking drift in provisioner TTLs,
/// while preserving the production invariant that rendered claims come only
/// from active policy rows.
pub fn active_provisioner_claims(model: &SiteModel, name: &str) -> Result<Value> {
    let provisioner = model
        .policy
        .provisioners
        .iter()
        .find(|entry| entry.name == name && entry.status.is_active())
        .ok_or_else(|| Error::Validation {
            field: format!("{CA_POLICY_PATH}:provisioners:{name}"),
            message: "missing active provisioner".to_owned(),
        })?;
    provisioner_claims(provisioner)
}

fn provisioner_claims(provisioner: &Provisioner) -> Result<Value> {
    let claims = match provisioner.role.as_str() {
        PROVISIONER_ROLE_HOST_BOOTSTRAP => json!({
            "defaultHostSSHCertDuration": provisioner.default_ttl,
            "maxHostSSHCertDuration": step_max_ttl(&provisioner.max_ttl),
            "enableSSHCA": true
        }),
        PROVISIONER_ROLE_USER_ENROLLMENT => json!({
            "defaultUserSSHCertDuration": provisioner.default_ttl,
            "maxUserSSHCertDuration": step_max_ttl(&provisioner.max_ttl),
            "enableSSHCA": true
        }),
        other => {
            return Err(Error::Validation {
                field: ca_policy_field("provisioners", &provisioner.role, "role"),
                message: format!("rendering provisioner role {other} is not implemented"),
            });
        }
    };
    Ok(claims)
}

fn test_jwk_provisioner(provisioner: &Provisioner) -> Result<Value> {
    Ok(json!({
        "type": "JWK",
        "name": provisioner.name,
        "key": {
            "use": "sig",
            "kty": "EC",
            "kid": format!("grafhome-ca-test-{}", provisioner.name),
            "crv": "P-256",
            "alg": "ES256",
            "x": "ZBlbApWR0lk8PU1b3AWX4aFCKw-ZjFs-EazBUTNvvtA",
            "y": "hq49jJukEJ5X9Gcu-akYcMlQQoGzK8iwJF_Xou-tA3g"
        },
        "claims": provisioner_claims(provisioner)?
    }))
}

pub(crate) fn provisioner_placeholder(name: &str) -> String {
    format!(
        "RUNTIME_SECRET_PLACEHOLDER:{}",
        provisioner_object_secret_name(name)
    )
}

fn provisioner_object_secret_name(name: &str) -> String {
    let suffix = name
        .bytes()
        .map(|byte| match byte {
            b'a'..=b'z' => (byte as char).to_ascii_uppercase(),
            b'A'..=b'Z' | b'0'..=b'9' => byte as char,
            _ => '_',
        })
        .collect::<String>();
    format!("GRAFHOME_CA_PROVISIONER_{suffix}_JSON")
}

fn authorized_principals(model: &SiteModel, host: &Host) -> Result<Vec<RenderedFile>> {
    let mut by_account = BTreeMap::<String, Vec<String>>::new();
    for access in model
        .policy
        .active_ssh_access()
        .filter(|access| access.host == host.host)
    {
        let user = model
            .policy
            .user(&access.user)
            .ok_or_else(|| Error::Validation {
                field: host_policy_field(&access.host, "user_access"),
                message: "missing policy user".to_owned(),
            })?;
        by_account
            .entry(access.unix_account.clone())
            .or_default()
            .push(user.principal.clone());
    }

    if let Some(path) = model
        .deployment
        .values
        .get("GRAFHOME_CA_AUTH_PRINCIPALS_FILE")
    {
        let mut principals = by_account.into_values().flatten().collect::<Vec<_>>();
        principals.sort();
        principals.dedup();
        return Ok(vec![RenderedFile {
            path: host_path(&host.host, path)?,
            mode: 0o644,
            content: format!("{}\n", principals.join("\n")),
        }]);
    }

    let mut files = Vec::new();
    for (account, mut principals) in by_account {
        principals.sort();
        principals.dedup();
        files.push(RenderedFile {
            path: host_path(
                &host.host,
                absolute_child(
                    &model.deployment.values["GRAFHOME_CA_AUTH_PRINCIPALS_DIR"],
                    account,
                )?,
            )?,
            mode: 0o644,
            content: format!("{}\n", principals.join("\n")),
        });
    }
    Ok(files)
}

/// Client `ssh_config` block that makes every site SSH server CA-only.
///
/// Without it, a host whose certificate is expired, revoked, or does not name
/// it still connects through any plain key in `~/.ssh/known_hosts` or
/// `/etc/ssh/ssh_known_hosts`, and ssh offers to save one when none exists.
/// For the policy's server principals the block therefore narrows host-key
/// sources to the CA trust file alone (which holds only `@cert-authority`
/// lines) and turns off the other ways ssh can accept a plain key: SSHFP DNS
/// records and a known-hosts command.
///
/// `Match final host` is evaluated on ssh's last configuration pass, after
/// `HostName` substitution and any hostname canonicalization, so an alias or
/// short name that resolves to a principal is covered. Plain `Match host`
/// would let a first pass for the short name pick up the `Host *`-style
/// defaults, which then win because ssh keeps the first value it reads; the
/// fragment's defaults are final-pass only for the same reason. Names outside
/// the policy, such as raw addresses or unmanaged devices, keep normal
/// known-hosts checking. With no SSH servers the block is omitted, since an
/// empty `Match host` list is invalid.
fn ca_only_host_block(principals: &[String], trust_dir: &str) -> String {
    if principals.is_empty() {
        return String::new();
    }
    format!(
        "# Site SSH servers are trusted only through the host CA. Saved keys are\n\
         # ignored, and a missing, expired, revoked, or misnamed host certificate\n\
         # fails the connection instead of prompting to trust the key.\n\
         Match final host {}\n    \
         UserKnownHostsFile none\n    \
         GlobalKnownHostsFile {trust_dir}/ssh_known_hosts\n    \
         StrictHostKeyChecking yes\n    \
         VerifyHostKeyDNS no\n    \
         KnownHostsCommand none\n    \
         UpdateHostKeys no\n",
        principals.join(",")
    )
}

fn render_template(template: &str, variables: &BTreeMap<String, String>) -> Result<String> {
    let mut rendered = template.to_owned();
    for (key, value) in variables {
        rendered = rendered.replace(&format!("${{{key}}}"), value);
    }
    if let Some(start) = rendered.find("${GRAFHOME_CA_") {
        let end = rendered[start..]
            .find('}')
            .map(|offset| start + offset + 1)
            .unwrap_or(rendered.len());
        return Err(Error::Validation {
            field: "render".to_owned(),
            message: format!("unresolved template variable {}", &rendered[start..end]),
        });
    }
    Ok(rendered)
}

fn absolute_child(parent: impl AsRef<str>, child: impl AsRef<str>) -> Result<PathBuf> {
    let parent = Path::new(parent.as_ref());
    if !parent.is_absolute() {
        return Err(Error::Validation {
            field: parent.display().to_string(),
            message: "expected absolute path".to_owned(),
        });
    }
    Ok(parent.join(child.as_ref()))
}

fn host_path(host: &str, path: impl AsRef<Path>) -> Result<PathBuf> {
    let mut relative = PathBuf::from("hosts").join(host);
    let path = path.as_ref();
    if path.is_absolute() {
        for component in path.components() {
            match component {
                Component::RootDir => {}
                Component::Normal(part) => relative.push(part),
                _ => {
                    return Err(Error::Validation {
                        field: path.display().to_string(),
                        message: "unsupported path component".to_owned(),
                    });
                }
            }
        }
    } else {
        relative.push(path);
    }
    ensure_relative(&relative)?;
    Ok(relative)
}

fn ensure_relative(path: &Path) -> Result<()> {
    if path.is_absolute()
        || path
            .components()
            .any(|component| matches!(component, Component::ParentDir))
    {
        Err(Error::Validation {
            field: path.display().to_string(),
            message: "rendered path must be relative and stay under the output directory"
                .to_owned(),
        })
    } else {
        Ok(())
    }
}

fn prepare_output_root(out_dir: &Path) -> Result<()> {
    if out_dir.exists() {
        ensure_not_symlink(out_dir)?;
        if !out_dir.is_dir() {
            return Err(Error::Validation {
                field: out_dir.display().to_string(),
                message: "render output path must be a directory".to_owned(),
            });
        }
    } else {
        std::fs::create_dir_all(out_dir).map_err(|source| Error::io(out_dir, source))?;
    }
    Ok(())
}

fn ensure_no_symlink_components(root: &Path, path: &Path) -> Result<()> {
    let relative = path.strip_prefix(root).map_err(|_| Error::Validation {
        field: path.display().to_string(),
        message: "render path escaped output directory".to_owned(),
    })?;
    let mut current = root.to_path_buf();
    ensure_not_symlink(&current)?;
    for component in relative.components() {
        match component {
            Component::Normal(part) => {
                current.push(part);
                ensure_not_symlink(&current)?;
            }
            Component::CurDir => {}
            _ => {
                return Err(Error::Validation {
                    field: path.display().to_string(),
                    message: "unsupported staging path component".to_owned(),
                });
            }
        }
    }
    Ok(())
}

fn create_dir_all_without_symlinks(root: &Path, path: &Path) -> Result<()> {
    let relative = path.strip_prefix(root).map_err(|_| Error::Validation {
        field: path.display().to_string(),
        message: "render path escaped output directory".to_owned(),
    })?;
    let mut current = root.to_path_buf();
    ensure_not_symlink(&current)?;
    for component in relative.components() {
        match component {
            Component::Normal(part) => {
                current.push(part);
                match std::fs::symlink_metadata(&current) {
                    Ok(metadata) if metadata.file_type().is_symlink() => {
                        return Err(Error::Validation {
                            field: current.display().to_string(),
                            message: "refusing to render through symlinked staging path".to_owned(),
                        });
                    }
                    Ok(metadata) if metadata.is_dir() => {}
                    Ok(_) => {
                        return Err(Error::Validation {
                            field: current.display().to_string(),
                            message: "render staging path component must be a directory".to_owned(),
                        });
                    }
                    Err(source) if source.kind() == std::io::ErrorKind::NotFound => {
                        std::fs::create_dir(&current)
                            .map_err(|source| Error::io(&current, source))?;
                        ensure_not_symlink(&current)?;
                    }
                    Err(source) => return Err(Error::io(&current, source)),
                }
            }
            Component::CurDir => {}
            _ => {
                return Err(Error::Validation {
                    field: path.display().to_string(),
                    message: "unsupported staging path component".to_owned(),
                });
            }
        }
    }
    ensure_no_symlink_components(root, path)
}

fn ensure_not_symlink(path: &Path) -> Result<()> {
    match std::fs::symlink_metadata(path) {
        Ok(metadata) if metadata.file_type().is_symlink() => Err(Error::Validation {
            field: path.display().to_string(),
            message: "refusing to render through symlinked staging path".to_owned(),
        }),
        Ok(_) => Ok(()),
        Err(source) if source.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(source) => Err(Error::io(path, source)),
    }
}

