    fn referenced_sshd_files(content: &str) -> Vec<&str> {
        content
            .lines()
            .filter_map(|line| {
                let mut parts = line.split_whitespace();
                let key = parts.next()?;
                if matches!(key, "TrustedUserCAKeys" | "RevokedKeys") {
                    parts.next()
                } else {
                    None
                }
            })
            .collect()
    }
